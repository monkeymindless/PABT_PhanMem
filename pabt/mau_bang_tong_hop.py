def _mau(c):
    return 'FF' + c if c else None


def tao_workbook():
    """Workbook mới, một sheet bảng tổng hợp (A3 ngang) - cùng nội dung / định dạng mẫu IN_BANGTONGHOP cũ."""
    from openpyxl.utils import get_column_letter
    from openpyxl.utils.indexed_list import IndexedList
    wb = openpyxl.Workbook()
    # phông mặc định của workbook = Arial 11 như mẫu Excel cũ: in_an._mdw đổi bề rộng cột sang px theo phông này (Calibri 11 lệch 1 px / ký tự)
    wb._fonts = IndexedList([Font(name='Arial', sz=11, family=2)])
    ws = wb.active
    ws.title = TEN_SHEET
    kieu = []
    for (phong, co, dam, nghieng, gach, mau_chu, nen, ngang, doc, xuong, thut, xoay, vien, so) in KIEU:
        f = Font(name=phong, sz=co, b=dam, i=nghieng, u='single' if gach else None, color=_mau(mau_chu))
        b = Border(*[Side(style=v[1], color=_mau(v[2])) if v else Side() for v in vien])
        kieu.append((f, b, PatternFill('solid', fgColor=_mau(nen)) if nen else PatternFill(), Alignment(
            horizontal=ngang, vertical=doc, wrap_text=xuong, indent=thut, text_rotation=xoay), so))
    for r, c, v, i in CELLS:
        o = ws.cell(r, c)
        if v is not None:
            o.value = v
        o.font, o.border, o.fill, o.alignment, o.number_format = kieu[i]
    for m in MERGES:
        ws.merge_cells(m)
    from openpyxl.utils import column_index_from_string
    for k, w in RONG_COT.items():
        cd = ws.column_dimensions[k]
        cd.min = cd.max = column_index_from_string(k)        # như mẫu đọc từ file: in_an._px_cot dựa vào min / max của từng cột
        cd.width = w
    for k in COT_AN:
        ws.column_dimensions[k].hidden = True
    for r, h in CAO_DONG.items():
        ws.row_dimensions[r].height = h
    for k, v in LE_TRANG.items():
        setattr(ws.page_margins, k, v)
    ws.page_setup.paperSize = 9
    ws.page_setup.orientation = 'landscape'
    ws.sheet_properties.pageSetUpPr = openpyxl.worksheet.properties.PageSetupProperties(fitToPage=True)
    ws.sheet_view.zoomScale = PHONG_TO
    ws.print_area = 'A1:%s%d' % (get_column_letter(SO_COT), SO_DONG)
    ws.print_title_rows = '9:12'
    ws.sheet_format.defaultRowHeight = 21.0          # như mẫu Excel cũ (dòng không đặt cao riêng)
    ws.sheet_format.defaultColWidth = 9.59765625
    ws.page_setup.fitToHeight = 0
    ws.sheet_view.zoomScaleNormal = PHONG_TO
    return wb

